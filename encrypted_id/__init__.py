# ---------------------------------------------------------------------------
# Shared helpers
# ---------------------------------------------------------------------------

_AES_KEY_LEN = 32
_AES_IV_LEN = 16
_MESSAGE_LEN = 16

_EKEY_CT_LEN = 8
_EKEY_TAG_LEN = 16
_EKEY_RAW_LEN = _EKEY_CT_LEN + _EKEY_TAG_LEN  # 24 → 32 base64url chars

_BASE62 = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz"
_SKEY_LEN = 9
_SKEY_MAC_BITS = 16
_SKEY_MAC_MASK = (1 << _SKEY_MAC_BITS) - 1
_SKEY_DOMAIN_BITS = 48
_SKEY_DOMAIN_MASK = (1 << _SKEY_DOMAIN_BITS) - 1
_MASK24 = 0xFFFFFF
_SKEY_FEISTEL_ROUNDS = 6
_UINT32_MAX = 2**32
_UINT64_MAX = 2**64


class EncryptedIDDecodeError(Exception):
    def __init__(self, msg="Failed to decrypt, invalid input."):
        super().__init__(msg)


def _secret_list():
    return getattr(settings, "SECRET_KEYS", None) or [settings.SECRET_KEY]


def _require_int_id(the_id, max_exclusive):
    if not isinstance(the_id, int) or isinstance(the_id, bool):
        raise TypeError("the_id must be an integer")
    if the_id < 0 or the_id >= max_exclusive:
        raise ValueError(
            "the_id must be in range [0, %d)" % max_exclusive
        )


def _to_ascii_bytes(token):
    if token is None:
        raise EncryptedIDDecodeError()
    if isinstance(token, str):
        try:
            return token.encode("ascii")
        except UnicodeEncodeError as exc:
            raise EncryptedIDDecodeError() from exc
    if isinstance(token, bytearray):
        return bytes(token)
    if isinstance(token, bytes):
        return token
    raise EncryptedIDDecodeError()


def _b64url_encode(raw):
    return base64.urlsafe_b64encode(raw).rstrip(b"=").decode("ascii")


def _b64url_decode(token_bytes):
    try:
        padding = (3 - len(token_bytes) % 3) * b"="
        return base64.urlsafe_b64decode(token_bytes + padding)
    except (TypeError, binascii.Error) as exc:
        raise EncryptedIDDecodeError() from exc


def get_model_sub_key(m):
    try:
        return m._meta.ek_key
    except AttributeError:
        return m._meta.db_table


def coerce_int_pk(pk, *, for_skey=False):
    """Normalize a model pk to a Python int for encryption."""
    if pk is None:
        raise ValueError("Cannot encrypt an unsaved model instance (pk is None)")
    if isinstance(pk, bool) or not isinstance(pk, int):
        try:
            if isinstance(pk, float):
                raise TypeError
            pk = int(pk)
        except (TypeError, ValueError) as exc:
            raise TypeError(
                "encrypted_id requires an integer primary key; got %r"
                % (type(pk).__name__,)
            ) from exc
    if for_skey and (pk < 0 or pk >= _UINT32_MAX):
        raise ValueError(
            "skey requires pk in [0, 2**32); got %s. Use ekey for larger ids."
            % pk
        )
    if not for_skey and (pk < 0 or pk >= _UINT64_MAX):
        raise ValueError("ekey requires pk in [0, 2**64); got %s" % pk)
    return pk


# ---------------------------------------------------------------------------
# ekey — AES-256-SIV, 64-bit id (32-char URL-safe token)
# ---------------------------------------------------------------------------

def _ekey_siv_key(secret, sub_key):
    """64-byte key material for AES-256-SIV."""
    material = "%s\0%s\0ekey-siv-v1" % (secret, sub_key)
    return hashlib.sha512(material.encode("utf-8")).digest()


def encode_ekey(the_id, sub_key):
    """Encrypt a 64-bit id with AES-256-SIV into a 32-character ekey."""
    _require_int_id(the_id, _UINT64_MAX)
    plaintext = struct.pack(">Q", the_id)
    key = _ekey_siv_key(settings.SECRET_KEY, sub_key)
    cipher = AES.new(key, AES.MODE_SIV)
    cipher.update(sub_key.encode("utf-8"))
    ciphertext, tag = cipher.encrypt_and_digest(plaintext)
    assert len(ciphertext) == _EKEY_CT_LEN and len(tag) == _EKEY_TAG_LEN
    return _b64url_encode(ciphertext + tag)


def decode_ekey(token, sub_key):
    """Decrypt an ekey produced by :func:`encode_ekey`."""
    raw = _b64url_decode(_to_ascii_bytes(token))
    if len(raw) != _EKEY_RAW_LEN:
        raise EncryptedIDDecodeError("Invalid ekey length.")

    ciphertext, tag = raw[:_EKEY_CT_LEN], raw[_EKEY_CT_LEN:]
    ad = sub_key.encode("utf-8")

    for secret in _secret_list():
        try:
            cipher = AES.new(_ekey_siv_key(secret, sub_key), AES.MODE_SIV)
            cipher.update(ad)
            plaintext = cipher.decrypt_and_verify(ciphertext, tag)
        except (ValueError, KeyError):
            continue
        if len(plaintext) != 8:
            continue
        (the_id,) = struct.unpack(">Q", plaintext)
        return the_id

    raise EncryptedIDDecodeError("Failed to decrypt ekey.")


# ---------------------------------------------------------------------------
# skey — 32-bit id + 16-bit MAC, Feistel, base62 (9 characters)
# ---------------------------------------------------------------------------

def _skey_hmac_key(secret, sub_key):
    material = "%s\0%s\0skey-v1" % (secret, sub_key)
    return hashlib.sha256(material.encode("utf-8")).digest()


def _skey_mac(key, the_id):
    digest = hmac.new(
        key, struct.pack(">I", the_id), hashlib.sha256
    ).digest()
    return int.from_bytes(digest[:2], "big") & _SKEY_MAC_MASK


def _round_f(key, round_idx, right24):
    digest = hmac.new(
        key,
        struct.pack(">BI", round_idx, right24),
        hashlib.sha256,
    ).digest()
    return int.from_bytes(digest[:3], "big") & _MASK24


def _feistel48_encrypt(value, key):
    left = (value >> 24) & _MASK24
    right = value & _MASK24
    for i in range(_SKEY_FEISTEL_ROUNDS):
        left, right = right, left ^ _round_f(key, i, right)
    return ((left << 24) | right) & _SKEY_DOMAIN_MASK


def _feistel48_decrypt(value, key):
    left = (value >> 24) & _MASK24
    right = value & _MASK24
    for i in range(_SKEY_FEISTEL_ROUNDS - 1, -1, -1):
        left, right = right ^ _round_f(key, i, left), left
    return ((left << 24) | right) & _SKEY_DOMAIN_MASK


def _to_base62(n, width=_SKEY_LEN):
    if n < 0 or n >= 62**width:
        raise EncryptedIDDecodeError("Value out of base62 range.")
    chars = []
    for _ in range(width):
        n, rem = divmod(n, 62)
        chars.append(_BASE62[rem])
    return "".join(reversed(chars))


def _from_base62(token):
    if not isinstance(token, str) or len(token) != _SKEY_LEN:
        raise EncryptedIDDecodeError("Invalid skey length.")
    n = 0
    for ch in token:
        idx = _BASE62.find(ch)
        if idx < 0:
            raise EncryptedIDDecodeError("Invalid skey character.")
        n = n * 62 + idx
    return n


def encode_skey(the_id, sub_key):
    """Encrypt a 32-bit id into a 9-character base62 skey."""
    _require_int_id(the_id, _UINT32_MAX)
    key = _skey_hmac_key(settings.SECRET_KEY, sub_key)
    packed = ((the_id << _SKEY_MAC_BITS) | _skey_mac(key, the_id)) & _SKEY_DOMAIN_MASK
    return _to_base62(_feistel48_encrypt(packed, key))


def decode_skey(token, sub_key):
    """Decrypt an skey produced by :func:`encode_skey`."""
    if token is None:
        raise EncryptedIDDecodeError()
    if isinstance(token, bytes):
        try:
            token = token.decode("ascii")
        except UnicodeDecodeError as exc:
            raise EncryptedIDDecodeError() from exc

    try:
        encrypted = _from_base62(token)
    except EncryptedIDDecodeError:
        raise

    for secret in _secret_list():
        key = _skey_hmac_key(secret, sub_key)
        packed = _feistel48_decrypt(encrypted, key)
        the_id = packed >> _SKEY_MAC_BITS
        mac = packed & _SKEY_MAC_MASK
        if the_id < _UINT32_MAX and mac == _skey_mac(key, the_id):
            return the_id

    raise EncryptedIDDecodeError("Failed to decrypt skey.")


# ---------------------------------------------------------------------------
# Legacy CBC + CRC encode/decode (django-encrypted-id ≤ 0.3.x tokens)
# ---------------------------------------------------------------------------

def _aes_key(secret):
    """Historical AES key: ``secret[:32].encode("utf-8")``."""
    key = secret[:_AES_KEY_LEN].encode("utf-8")
    if len(key) not in (16, 24, 32):
        raise ValueError(
            "SECRET_KEY[:32] must encode to 16, 24, or 32 bytes for "
            "encrypted_id AES; got %d bytes." % len(key)
        )
    return key


def _aes_iv(secret, sub_key):
    return hashlib.sha256((secret + sub_key).encode("ascii")).digest()[:_AES_IV_LEN]


def encode(the_id, sub_key):
    """Legacy CBC+CRC token (22 chars). Prefer :func:`encode_ekey`."""
    _require_int_id(the_id, _UINT64_MAX)

    version = 1
    crc = binascii.crc32(str(the_id).encode("utf-8")) & 0xFFFFFFFF
    message = struct.pack(b"<IQI", crc, the_id, version)
    assert len(message) == _MESSAGE_LEN

    secret = settings.SECRET_KEY
    cipher = AES.new(_aes_key(secret), AES.MODE_CBC, iv=_aes_iv(secret, sub_key))
    return _b64url_encode(cipher.encrypt(message))


def decode(e, sub_key):
    """Decode a legacy CBC+CRC token. Prefer :func:`decode_ekey`."""
    e = _to_ascii_bytes(e)

    forced_version = None
    if e.startswith(b"$"):
        forced_version = 1
        e = e[1:]

    e = _b64url_decode(e)

    for secret in _secret_list():
        try:
            cipher = AES.new(
                _aes_key(secret), AES.MODE_CBC, iv=_aes_iv(secret, sub_key)
            )
            msg = cipher.decrypt(e)
        except (ValueError, TypeError):
            continue

        try:
            crc, the_id, version = struct.unpack(b"<IQI", msg)
        except struct.error:
            continue

        if forced_version is not None:
            version = forced_version

        try:
            if version == 0:
                expected_crc = binascii.crc32(bytes(the_id)) & 0xFFFFFFFF
            else:
                expected_crc = (
                    binascii.crc32(str(the_id).encode("utf-8")) & 0xFFFFFFFF
                )
        except (MemoryError, OverflowError):
            continue

        if crc == expected_crc:
            return the_id

    raise EncryptedIDDecodeError("Failed to decrypt, CRC never matched.")


# ---------------------------------------------------------------------------
# Model helpers
# ---------------------------------------------------------------------------

def ekey(instance):
    """Return the AES-SIV ekey for a saved model instance."""
    if not isinstance(instance, Model):
        raise TypeError("ekey() expects a Django model instance")
    return encode_ekey(
        coerce_int_pk(instance.pk, for_skey=False),
        get_model_sub_key(instance),
    )


def skey(instance):
    """Return the short base62 skey for a saved model instance."""
    if not isinstance(instance, Model):
        raise TypeError("skey() expects a Django model instance")
    return encode_skey(
        coerce_int_pk(instance.pk, for_skey=True),
        get_model_sub_key(instance),
    )


def get_object_or_404(m, token, *arg, **kw):
    """Resolve an **ekey** (AES-SIV) to a model instance or raise Http404."""
    try:
        pk = decode_ekey(token, get_model_sub_key(m))
    except EncryptedIDDecodeError as exc:
        raise Http404(
            "No %s matches the given encrypted id." % m._meta.object_name
        ) from exc
    return go4(m, pk=pk, *arg, **kw)


def get_object_or_404_skey(m, token, *arg, **kw):
    """Resolve an **skey** to a model instance or raise Http404."""
    try:
        pk = decode_skey(token, get_model_sub_key(m))
    except EncryptedIDDecodeError as exc:
        raise Http404(
            "No %s matches the given short encrypted id." % m._meta.object_name
        ) from exc
    return go4(m, pk=pk, *arg, **kw)
