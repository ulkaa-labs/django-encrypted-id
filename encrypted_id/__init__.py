"""Encrypted integer primary keys for Django models.

Two token formats are provided:

* **ekey** — AES-256-SIV authenticated encryption of a 64-bit id
  (URL-safe base64, 32 characters). Prefer this for public URLs when
  length is not constrained.
* **skey** — 32-bit id + 16-bit MAC, Feistel-encrypted, base62-encoded
  (always 9 characters). Prefer this for short URLs; pk must fit in
  ``uint32`` (Django ``AutoField`` is fine).

Legacy CBC+CRC ``encode`` / ``decode`` remain for tokens generated by
django-encrypted-id ≤ 0.3.x.
"""

from Cryptodome.Cipher import AES

import base64
import binascii
import hashlib
import hmac
import struct

from django.conf import settings
from django.db.models import Model
from django.http import Http404
from django.shortcuts import get_object_or_404 as go4


